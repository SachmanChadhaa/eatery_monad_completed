// Regenerates src/abi.ts from the Foundry build output. Run `forge build` in contracts/ first.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const abiOf = (name) =>
  JSON.parse(readFileSync(resolve(here, `../../../contracts/out/${name}.sol/${name}.json`), 'utf8')).abi

const orders = abiOf('CanteenOrders')
const cinr = abiOf('CINR')
const out = `// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit by hand.
export const canteenOrdersAbi = ${JSON.stringify(orders, null, 2)} as const

export const cinrAbi = ${JSON.stringify(cinr, null, 2)} as const
`
writeFileSync(resolve(here, '../src/abi.ts'), out)
console.log(`wrote src/abi.ts (CanteenOrders ${orders.length} entries, CINR ${cinr.length})`)
